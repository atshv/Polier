"""Saved views (2.1): named filters, grouping and sorting, stored as files.

A view is a small committed JSON file in ``views/<id>.json``::

    {"version": 1, "id": "review-queue", "name": "Review queue", "kind": "table",
     "filters": [{"field": "status", "op": "any_of", "value": ["review", "verifying"]}],
     "group_by": "owner", "sort": {"field": "id", "dir": "asc"},
     "columns": ["title", "status", "owner"], "created_by": "owner"}

Project-wide views are committed so the team (and every agent) sees them; the
personal default view and UI preferences stay in the dashboard runtime config.
Built-in views are generated by ``core.filters.builtin_views`` and are not
files, so an update never overwrites user data.
"""
from __future__ import annotations

import json
import os
import re
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

from . import filters
from .errors import PolierError
from .runs import FileLock

DIR = "views"
VERSION = 1
ID = re.compile(r"^[a-z][a-z0-9-]{0,40}$")
KINDS = ("board", "table")
COLUMNS = (
    "id", "title", "status", "stage", "package", "owner", "labels", "complexity",
    "estimate_hours", "tokens", "gates", "attempt", "review", "claim",
)
FIELDS = frozenset({"version", "id", "name", "kind", "filters", "group_by", "sort",
                    "columns", "created_by", "created"})


def folder(root) -> Path:
    return Path(root) / DIR


def _path(root, view_id: str) -> Path:
    if not ID.match(view_id or ""):
        raise PolierError("view id must be lowercase (a-z, 0-9, '-')")
    return folder(root) / f"{view_id}.json"


def errors(view: Dict[str, Any]) -> List[str]:
    if not isinstance(view, dict):
        return ["view must be an object"]
    found: List[str] = []
    for field in sorted(set(view) - FIELDS):
        found.append(f"view: unknown field {field!r}")
    if view.get("version") not in (None, VERSION):
        found.append(f"view: version must be {VERSION}")
    if not isinstance(view.get("id"), str) or not ID.match(view["id"]):
        found.append("view: id must be lowercase (a-z, 0-9, '-')")
    name = view.get("name")
    if not isinstance(name, str) or not 1 <= len(name.strip()) <= 80:
        found.append("view: name must be 1–80 characters")
    if view.get("kind", "board") not in KINDS:
        found.append(f"view: kind must be one of {', '.join(KINDS)}")
    found.extend(filters.validate(view.get("filters")))
    if view.get("group_by") is not None and view.get("group_by") not in filters.GROUP_BY:
        found.append(f"view: group_by must be one of {', '.join(str(item) for item in filters.GROUP_BY)}")
    sort = view.get("sort")
    if sort is not None:
        if not isinstance(sort, dict) or set(sort) - {"field", "dir"}:
            found.append("view: sort must be {field, dir}")
        else:
            if sort.get("field") not in filters.SORTABLE:
                found.append(f"view: cannot sort by {sort.get('field')!r}")
            if sort.get("dir", "asc") not in ("asc", "desc"):
                found.append("view: sort.dir must be asc or desc")
    columns = view.get("columns")
    if columns is not None:
        if not isinstance(columns, list) or any(column not in COLUMNS for column in columns):
            found.append(f"view: columns must be a list of {', '.join(COLUMNS)}")
    return found


def load_all(root) -> List[Dict[str, Any]]:
    """Every valid saved view, sorted by name; broken files are skipped."""
    base = folder(root)
    if not base.is_dir():
        return []
    views: List[Dict[str, Any]] = []
    for path in sorted(base.glob("*.json")):
        try:
            value = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if not isinstance(value, dict):
            continue
        value.setdefault("version", VERSION)
        if errors(value):
            continue
        views.append(value)
    views.sort(key=lambda view: str(view.get("name") or "").lower())
    return views


def save(root, payload: Dict[str, Any]) -> Dict[str, Any]:
    """Create or replace one view file after validation."""
    root = Path(root).resolve()
    view = dict(payload or {})
    view.setdefault("version", VERSION)
    view.setdefault("kind", "board")
    problems = errors(view)
    if problems:
        raise PolierError("; ".join(problems))
    target = _path(root, str(view["id"]))
    target.parent.mkdir(parents=True, exist_ok=True)
    with FileLock(target.parent / ".views.lock"):
        temporary = target.with_name(f"{target.name}.{os.getpid()}.{time.time_ns()}.tmp")
        temporary.write_text(json.dumps(view, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        os.replace(temporary, target)
    return view


def delete(root, view_id: str) -> Dict[str, Any]:
    root = Path(root).resolve()
    target = _path(root, view_id)
    with FileLock(target.parent / ".views.lock"):
        if not target.is_file():
            raise KeyError(view_id)
        target.unlink()
    return {"id": view_id, "deleted": True}


def all_views(root, me: Optional[str] = None) -> List[Dict[str, Any]]:
    """Built-in views first, then saved ones (a saved id replaces the built-in)."""
    builtin = {view["id"]: view for view in filters.builtin_views(me)}
    saved = {view["id"]: view for view in load_all(root)}
    merged = list(builtin.values()) + [view for view_id, view in saved.items() if view_id not in builtin]
    return merged
