// Generate docs/tools.md from the plugin's tool definitions, so the reference
// can never drift from what the model sees.
//
//   node scripts/tools-doc.mjs           write docs/tools.md
//   node scripts/tools-doc.mjs --stdout  print it (scripts/check.py compares)
import { writeFileSync } from 'node:fs'
import path from 'node:path'

import { resolveConfig } from '../plugin/index.mjs'
import { GUIDE } from '../plugin/lib/context.mjs'
import { tools } from '../plugin/lib/tools.mjs'

const ROOT = path.resolve(import.meta.dirname, '..')

function type(schema) {
  if (!schema) return ''
  if (schema.enum) return schema.enum.map((v) => `\`${v}\``).join(' · ')
  if (schema.type === 'array') return `list of ${schema.items?.type ?? 'values'}`
  return schema.type ?? ''
}

export function render() {
  const lines = [
    '# Tool reference',
    '',
    '> Generated by `node scripts/tools-doc.mjs` from `plugin/lib/tools.mjs`. Do not edit by hand.',
    '',
    'The DeepSeek Harness plugin registers these tools for the model. The human never calls them: the agent maps plain language to them, and the ones that need a human decision open a DSH approval prompt.',
    '',
  ]
  for (const def of tools({}, resolveConfig())) {
    lines.push(`## \`${def.name}\``, '', def.description, '')
    const props = Object.entries(def.parameters?.properties ?? {})
    if (props.length) {
      const required = new Set(def.parameters.required ?? [])
      lines.push('| Parameter | Type | Required | Meaning |', '| --- | --- | --- | --- |')
      for (const [name, schema] of props) {
        lines.push(`| \`${name}\` | ${type(schema)} | ${required.has(name) ? 'yes' : ''} | ${schema.description ?? ''} |`)
      }
      lines.push('')
    }
  }
  lines.push('## The guide in the system prompt', '', 'Sessions inside a Polier project get this section:', '', '```markdown', GUIDE, '```', '')
  return lines.join('\n')
}

if (process.argv.includes('--stdout')) process.stdout.write(render())
else {
  writeFileSync(path.join(ROOT, 'docs', 'tools.md'), render())
  console.log('written: docs/tools.md')
}
